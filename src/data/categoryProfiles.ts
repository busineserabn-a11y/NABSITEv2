// 2. HELPER TO RETRIEVE PROFILE (WITH FALLBACK)
// ---------------------------------------------------------------------------
export function getCategoryDesignProfile(categoryName?: string): CategoryDesignProfile {
  if (!categoryName) return CATEGORY_DESIGN_PROFILES['Restaurant'];

  const normalized = categoryName.trim();

  // 1. Direct match
  if (CATEGORY_DESIGN_PROFILES[normalized]) {
    return CATEGORY_DESIGN_PROFILES[normalized];
  }

  // 2. Case-insensitive or partial match
  const lower = normalized.toLowerCase();
  for (const [key, profile] of Object.entries(CATEGORY_DESIGN_PROFILES)) {
    if (
      key.toLowerCase() === lower ||
      profile.categorySlug.toLowerCase() === lower ||
      lower.includes(key.toLowerCase()) ||
      key.toLowerCase().includes(lower)
    ) {
      return profile;
    }
  }

  // 3. Category alias mapping
  if (lower.includes('school') || lower.includes('academy') || lower.includes('college') || lower.includes('edu')) {
    return CATEGORY_DESIGN_PROFILES['Education'];
  }
  if (lower.includes('coffee') || lower.includes('cafe') || lower.includes('café') || lower.includes('roast')) {
    return CATEGORY_DESIGN_PROFILES['Café'];
  }
  if (lower.includes('hotel') || lower.includes('resort') || lower.includes('lodge') || lower.includes('stay')) {
    return CATEGORY_DESIGN_PROFILES['Hotel'];
  }
  if (lower.includes('health') || lower.includes('clinic') || lower.includes('medical') || lower.includes('doctor') || lower.includes('hospital')) {
    return CATEGORY_DESIGN_PROFILES['Healthcare'];
  }
  if (lower.includes('beauty') || lower.includes('salon') || lower.includes('spa') || lower.includes('barber')) {
    return CATEGORY_DESIGN_PROFILES['Beauty & Salon'];
  }
  if (lower.includes('gym') || lower.includes('fitness') || lower.includes('workout') || lower.includes('crossfit')) {
    return CATEGORY_DESIGN_PROFILES['Fitness & Gym'];
  }

  // 4. Default fallback to Restaurant
  return CATEGORY_DESIGN_PROFILES['Restaurant'];
}

